"""Название группы из текста PDF ЕЭК: первая группа раздела начинается с примечаний раздела."""
from scripts.parse.ett_nomenclature import group_title


def test_title_follows_the_group_header():
    lines = ['ГРУППА 01 ', 'ЖИВЫЕ ЖИВОТНЫЕ ', 'Примечание: ', '1. В данную группу включаются все живые животные']
    assert group_title(lines, '01') == 'ЖИВЫЕ ЖИВОТНЫЕ'


def test_first_group_of_a_section_after_the_section_notes_and_a_page_break():
    # Раздел XVI в ru.84.pdf: примечания раздела, «ГРУППА 84» в конце страницы, название — на следующей
    lines = ['РАЗДЕЛ XVI', 'МАШИНЫ, ОБОРУДОВАНИЕ И МЕХАНИЗМЫ', 'Примечания:', '1. В данный раздел не включаются:',
             'примечания 1 к группе 84 и примечания 1 к группе 85, части машин', ' ', 'ГРУППА 84 ', '',
             ' ', 'РЕАКТОРЫ ЯДЕРНЫЕ, КОТЛЫ, ОБОРУДОВАНИЕ И МЕХАНИЧЕСКИЕ ', 'УСТРОЙСТВА; ИХ ЧАСТИ ', 'Примечания: ']
    assert group_title(lines, '84') == 'РЕАКТОРЫ ЯДЕРНЫЕ, КОТЛЫ, ОБОРУДОВАНИЕ И МЕХАНИЧЕСКИЕ УСТРОЙСТВА; ИХ ЧАСТИ'


def test_header_of_another_group_is_not_taken():
    lines = ['ГРУППА 85', 'ЭЛЕКТРИЧЕСКИЕ МАШИНЫ']
    assert group_title(lines, '84') == '' and group_title(lines, '8') == ''
